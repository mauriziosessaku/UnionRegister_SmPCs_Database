# ── 3. Helper ──────────────────────────────────────────────
def check(label, computed, expected, note=""):
    status = "✅ MATCH" if computed == expected else "❌ MISMATCH"
    print(f"\n{status}  |  {label}")
    print(f"   Expected : {expected:,}")
    print(f"   Computed : {computed:,}")
    if computed != expected:
        print(f"   Diff     : {computed - expected:+,}")
    if note:
        print(f"   Note     : {note}")

DATE_RE = re.compile(r'^(\d{4}-\d{2}-\d{2})_')

# ── 4. Scan all drug folders ───────────────────────────────
print("="*65)
print("SCANNING RAW DATA  (may take a few minutes on the full DB)")
print("="*65)

n_smpc_versions    = 0    # total .txt files across Latest/ + Updates/
all_dates          = []   # SmPC dates from Updates/ filenames
