"""# 🧬 **Part 6: Novelty Analysis & Drug Classification**
---
> *Extracting the first year of appearance for each PT and classifying drugs as Biologic/Targeted vs. Small Molecule based on INN suffixes.*
"""

import pandas as pd
import matplotlib.pyplot as plt

# 1. Prepare Data: Ensure 'Year Added' exists and is valid
# Convert 'Date Added' to datetime if needed, then extract Year
if 'Date Added' in df.columns:
    df['Date Added'] = pd.to_datetime(df['Date Added'], errors='coerce')
    df['Year Added'] = df['Date Added'].dt.year

# Filter out rows with missing Years or PTs
clean_df = df.dropna(subset=['MedDRA_PT_Term', 'Year Added']).copy()

# 2. Analysis: Find the first year each PT appeared
pt_first_year = clean_df.groupby('MedDRA_PT_Term')['Year Added'].min().reset_index(name='First_Seen_Year')

# Count how many *new* PTs were introduced each year
novelty_by_year = pt_first_year.groupby('First_Seen_Year').size().reset_index(name='New_PTs')

# Calculate Cumulative Sum
novelty_by_year['Cumulative_PTs'] = novelty_by_year['New_PTs'].cumsum()

# Classify by INN suffix as a proxy
biologics_keywords = ['mab', 'nib', 'zumab', 'ximab', 'lumab', 'tinib', 'rafenib', 'ciclib']
df['Drug_Type'] = df['inn'].apply(
    lambda x: 'Biologic/Targeted' if any(x.lower().endswith(k) for k in biologics_keywords)
    else 'Small Molecule' if pd.notna(x) else 'Unknown'
)
ae_per_drug = df.groupby('Brand_Name')['MedDRA_PT_Term'].nunique().reset_index(name='AE_Count')
ae_per_drug = ae_per_drug.merge(df[['Brand_Name','ATC_Level_1_Desc']].drop_duplicates(), on='Brand_Name')
soc_per_drug = df.groupby('Brand_Name')['MedDRA_SOC_Term'].nunique().reset_index(name='SOC_Count')
soc_per_drug = soc_per_drug.merge(df[['Brand_Name','ATC_Level_1_Desc']].drop_duplicates(), on='Brand_Name')

