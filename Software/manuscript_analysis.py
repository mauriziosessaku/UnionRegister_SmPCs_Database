# ── 3. Helper Function ─────────────────────────────────────
def check(label, computed, expected, is_pct=False, tolerance=0.2):
    """Validates computed values against expected text claims."""
    if is_pct or isinstance(computed, float):
        match = abs(computed - expected) <= tolerance
