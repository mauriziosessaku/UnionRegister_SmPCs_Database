#
#  File structure:
#    Col 0 — adverse event term
#    Col 1 — status: correct / duplicate / missing /
#                    missing-r / triplicate
# ============================================================

import os, glob
import pandas as pd
from collections import Counter
from tqdm.notebook import tqdm

# ── 1. Configuration ───────────────────────────────────────
FOLDER = "/content/extracted_data/Validation dataset"   # ← your validation folder

# ── 2. Load all files ──────────────────────────────────────
files = sorted(glob.glob(os.path.join(FOLDER, "*.xlsx")))
print(f"📂 Files found: {len(files)}\n")

# ── 3. Aggregate counts ────────────────────────────────────
VALID_STATUSES = {"correct", "duplicate", "missing", "missing-r", "triplicate"}

total_counter  = Counter()   # global counts
per_drug       = []          # one row per drug for the detail table
no_status_col  = []          # files with only 1 column (no status)
errors         = []

for f in tqdm(files, desc="Reading", unit="file"):
    drug_name = os.path.splitext(os.path.basename(f))[0]
    drug_name = drug_name.replace("_adverse_events", "")

    try:
        df = pd.read_excel(f)

        if len(df.columns) < 2:
            no_status_col.append(drug_name)
            continue

        # Status is always column index 1 regardless of column name
        statuses = (
            df.iloc[:, 1]
            .fillna("")
            .astype(str)
            .str.strip()
            .str.lower()
        )
        # Count only recognised statuses (ignore blanks)
        counts = Counter(s for s in statuses if s in VALID_STATUSES)

        total_counter.update(counts)

        n_total     = sum(counts.values())
        n_correct   = counts.get("correct", 0)
        n_dup       = counts.get("duplicate", 0)
        n_trip      = counts.get("triplicate", 0)
        n_missing   = counts.get("missing", 0) + counts.get("missing-r", 0)
        pct_correct = 100 * n_correct / n_total if n_total > 0 else None

        per_drug.append({
            "Drug":          drug_name,
            "Total":         n_total,
            "Correct":       n_correct,
            "Duplicate":     n_dup,
            "Triplicate":    n_trip,
            "Missing":       n_missing,
            "% Correct":     round(pct_correct, 2) if pct_correct is not None else None,
        })

    except Exception as e:
        errors.append(f"{drug_name}: {e}")

# ── 4. Global summary ──────────────────────────────────────
grand_total   = sum(total_counter.values())
n_correct     = total_counter.get("correct", 0)
n_dup         = total_counter.get("duplicate", 0)
n_trip        = total_counter.get("triplicate", 0)
n_missing     = total_counter.get("missing", 0) + total_counter.get("missing-r", 0)

pct_correct   = 100 * n_correct / grand_total if grand_total else 0
pct_dup       = 100 * n_dup     / grand_total if grand_total else 0
pct_trip      = 100 * n_trip    / grand_total if grand_total else 0
pct_missing   = 100 * n_missing / grand_total if grand_total else 0

print("\n" + "=" * 55)
print("  GLOBAL VALIDATION SUMMARY")
print("=" * 55)
print(f"  Files analysed          : {len(per_drug):>8,}")
print(f"  Files without status col: {len(no_status_col):>8,}")
print(f"  Total AE entries        : {grand_total:>8,}")
print("-" * 55)
print(f"  ✅ Correct              : {n_correct:>8,}   ({pct_correct:.2f}%)")
print(f"  🔁 Duplicate            : {n_dup:>8,}   ({pct_dup:.2f}%)")
print(f"  🔁 Triplicate           : {n_trip:>8,}   ({pct_trip:.2f}%)")
