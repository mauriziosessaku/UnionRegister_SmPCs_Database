def parse_atc_data(atc_string):
    """
    Safely parses the ATC string. Returns empty dict on ANY failure.
    """
    parsed_data = {}
    for i in range(1, 6):
        parsed_data[f'ATC_Level_{i}_Code'] = ''
        parsed_data[f'ATC_Level_{i}_Desc'] = ''

    # 1. Clean and Validation
    s_data = str(atc_string).strip()
    if s_data == '' or s_data.lower() == 'nan' or s_data == '[]':
        return parsed_data

    try:
        # 2. Attempt Parsing
        # Use ast.literal_eval for safe evaluation of Python-like structures
        data_structure = ast.literal_eval(s_data)

        # Unwrap outer lists (sometimes double nested [[...]])
        if isinstance(data_structure, list):
            while len(data_structure) > 0 and isinstance(data_structure[0], list):
                data_structure = data_structure[0]

            # Extract
            for item in data_structure:
                if isinstance(item, dict):
                    lvl = str(item.get('level', ''))
                    code = item.get('code', '')
                    desc = item.get('description', '')

                    if lvl in ['1', '2', '3', '4', '5']:
                        parsed_data[f'ATC_Level_{lvl}_Code'] = code
                        parsed_data[f'ATC_Level_{lvl}_Desc'] = desc

    except (ValueError, SyntaxError):
        # Allow malformed strings to fail silently without crashing the script
        pass
    except Exception:
        pass

    return parsed_data

