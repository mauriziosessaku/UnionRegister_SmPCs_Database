def _vis(s):
    return len(re.sub(r'\033\[[0-9;]*m', '', s))

def _pad(s, w, align='left'):
    d = w - _vis(s)
    return (s + ' '*max(0,d)) if align == 'left' else (' '*max(0,d) + s)

W = 76   # total box width

